/* نگاشت لینک‌های قدیمی فوتر/SPA به صفحات مستقل (صفر لینک شکسته) */
const ALIAS = {
  '/login': '/auth',
  '/blog': '/articles',
  '/portal': '/client-portal',
  '/why': '/why-dadgar',
  '/reviews': '/testimonials',
  '/reach': '/connect',
  '/expats': '/services/abroad-iranians',
  '/enterprise': '/services/corporate',
  '/service/family-inheritance': '/services/inheritance-family',
  '/service/tax-customs': '/services/tax-customs',
  '/service/arbitration': '/services/commercial-arbitration'
};

function pageFor(pathname) {
  let p = String(pathname || '').replace(/\/+$/, '') || '/';
  if (ALIAS[p]) p = ALIAS[p];
  else if (/^\/lawyer\//.test(p)) p = '/lawyers/profile';          /* /lawyer/1 → پروفایل وکیل */
  else if (/^\/post\//.test(p)) p = '/articles/detail';             /* /post/1 → جزئیات مقاله */
  else if (/^\/knowledge\/article\//.test(p)) p = '/articles/specialized-sample';
  return pages[p] || null;
}
module.exports = { pages, pageFor };
